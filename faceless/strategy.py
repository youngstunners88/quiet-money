"""The channel's strategy, kept current from its own numbers (`python -m faceless strategy`; the weekly scout runs it).

Two parts in channel/STRATEGY.md. The DATA block between the markers is rewritten on every run from the evidence: the latest public
snapshot, pillar rows, hold rates, the phone's receipts and the funnel. The JUDGMENT part after it is written by the review (skill
faceless-performance-review) and is never overwritten here. Every run also appends one row to analytics/strategy.jsonl, so the file
shows the trend, not just the latest number. Nothing here calls the network: it reads what the other lanes already recorded.
"""

from __future__ import annotations

import json
import re
import statistics
from datetime import datetime, timezone
from pathlib import Path

from faceless import config, scout
from faceless.config import Paths
from faceless.fsutil import read_jsonl, write_atomic

OUT = Paths.root / "channel" / "STRATEGY.md"
LOG = Paths.root / "analytics" / "strategy.jsonl"
SNAPS = Paths.root / "analytics" / "snapshots"
METRICS = Paths.root / "analytics" / "metrics.jsonl"
RECEIPTS = Paths.state / "phone" / "receipts.jsonl"
OFFERS = Paths.state / "offers.jsonl"
YPP = Paths.root / "analytics" / "ypp.jsonl"
SITE = Paths.root / "analytics" / "site.jsonl"
BEGIN = "<!-- data:begin (generated by python -m faceless strategy; do not edit this block) -->"
END = "<!-- data:end -->"
SIGNAL_N = 30                       # a group smaller than this is a signal, not a fact
STALE_DAYS = 7                      # a snapshot older than this is reported as stale

TITLE_TESTS = {
    "title has a number": lambda t: bool(re.search(r"\d", t)),
    "title has a $ or %": lambda t: bool(re.search(r"[$%]", t)),
    "abstract words (hidden, silent, brain, direction)": lambda t: bool(re.search(r"\b(hidden|silent|brains?|directions?)\b", t, re.I)),
    "starts with 'Why'": lambda t: t.lower().startswith("why"),
}


def _med(xs: list[float]) -> float | None:
    return round(statistics.median(xs), 1) if xs else None


def _mean(xs: list[float]) -> float | None:
    return round(statistics.fmean(xs), 1) if xs else None


def latest_snapshot() -> tuple[str, list[dict]] | None:
    """The newest public Shorts snapshot (`tools/perf-snapshot.py`): its date and [{title, views}]."""
    files = sorted(SNAPS.glob("youtube-*.json")) if SNAPS.exists() else []
    for f in reversed(files):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            return str(data["date"]), [s for s in data["shorts"] if "views" in s and "title" in s]
        except (OSError, ValueError, KeyError, TypeError):
            continue                                   # a damaged snapshot is skipped, the older one is used
    return None


def title_groups(shorts: list[dict]) -> list[tuple]:
    rows = []
    for name, pred in TITLE_TESTS.items():
        yes = [s["views"] for s in shorts if pred(s["title"])]
        no = [s["views"] for s in shorts if not pred(s["title"])]
        rows.append((name, len(yes), _med(yes), len(no), _med(no)))
    return rows


def pillar_rows() -> list[tuple]:
    """Median and mean views per pillar, one row per job (a job reported twice counts once: the later row wins)."""
    latest: dict[str, dict] = {}
    for r in read_jsonl(METRICS):
        if r.get("platform") == "youtube" and isinstance(r.get("views"), (int, float)):
            latest[r["job"]] = r
    by: dict[str, list[float]] = {}
    for r in latest.values():
        by.setdefault(r.get("pillar", "?"), []).append(float(r["views"]))
    return sorted(((p, len(v), _med(v), _mean(v)) for p, v in by.items()), key=lambda row: -(row[2] or 0))


def _offer_counts() -> str:
    """Offer rows in the ledger by status (one row per video); drafts are not live until they are pinned."""
    by: dict[str, set] = {}
    for r in read_jsonl(OFFERS):
        if r.get("video_id"):
            by.setdefault(str(r.get("status", "?")), set()).add(r["video_id"])
    if not by:
        return "none"
    return ", ".join(f"{k} {len(v)}" for k, v in sorted(by.items()))


def phone_counts() -> dict:
    """Posts the phone lane recorded, one per job (a job receipted twice counts once)."""
    jobs = {r.get("id"): r.get("kind", "?") for r in read_jsonl(RECEIPTS) if r.get("result") == "posted"}
    counts: dict[str, int] = {}
    for kind in jobs.values():
        counts[kind] = counts.get(kind, 0) + 1
    return counts


def evidence(today: str) -> dict:
    snap = latest_snapshot()
    shorts = snap[1] if snap else []
    views = [s["views"] for s in shorts]
    age = None
    if snap:
        age = (datetime.fromisoformat(today) - datetime.fromisoformat(snap[0])).days
    ypp = read_jsonl(YPP)[-1:] or [{}]
    site = read_jsonl(SITE)[-1:] or [{}]
    health = scout.health(days=7)
    return {
        "today": today,
        "snapshot": snap[0] if snap else None,
        "snapshot_age": age,
        "shorts": len(shorts),
        "mean": _mean(views),
        "median": _med(views),
        "max": max(views) if views else None,
        "zero": sum(1 for v in views if v <= 5),
        "titles": title_groups(shorts) if shorts else [],
        "pillars": pillar_rows(),
        "hold": health,
        "phone": phone_counts(),
        "offers": _offer_counts(),
        "subscribers": ypp[0].get("subscribers"),
        "ypp_note": ypp[0].get("note", ""),
        "pageviews": site[0].get("pageviews"),
        "site_day": site[0].get("day"),
    }


def trend_row(ev: dict) -> dict:
    return {"at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "snapshot": ev["snapshot"], "shorts": ev["shorts"],
            "mean": ev["mean"], "median": ev["median"], "zero": ev["zero"], "hold_rate": ev["hold"].get("hold_rate"),
            "subscribers": ev["subscribers"]}


def render(ev: dict, trend: list[dict]) -> str:
    L = [BEGIN, "", f"Generated {ev['today']} (UTC). Sources: the latest public snapshot, metrics.jsonl, the gauntlet reports, phone receipts, "
         "the YPP and site logs. Revenue is not wired into this file; the money desk is `python -m faceless cash`.", ""]
    if ev["snapshot_age"] is None:
        L += ["> **No public snapshot yet.** Run `tools/perf-snapshot.py` on the phone, then `python -m faceless strategy`.", ""]
    elif ev["snapshot_age"] > STALE_DAYS:
        L += [f"> **The snapshot is {ev['snapshot_age']} days old** ({ev['snapshot']}). The numbers below are that old. Refresh it on the phone.", ""]
    L += ["## Scoreboard", "", "| | Now |", "|---|---|",
          f"| Shorts with a public snapshot ({ev['snapshot'] or 'none'}) | {ev['shorts']} |",
          f"| Mean / median views per Short | {ev['mean']} / {ev['median']} |",
          f"| Best Short | {ev['max']} |",
          f"| Shorts at 5 views or fewer | {ev['zero']} of {ev['shorts']} |",
          f"| Subscribers | {ev['subscribers'] if ev['subscribers'] is not None else 'not pulled (YouTube quota)'} |",
          f"| Website pageviews (latest day {ev['site_day'] or 'none'}) | {ev['pageviews'] if ev['pageviews'] is not None else 'none'} |",
          f"| Offers in the ledger, by status | {ev['offers']} |",
          "| Revenue | not wired into this file |", ""]
    L += [f"## What the titles show (signals unless n >= {SIGNAL_N})", "", "| Feature | With it: n, median | Without it: n, median |", "|---|---|---|"]
    for name, yn, ym, nn, nm in ev["titles"]:
        flag = "" if min(yn, nn) >= SIGNAL_N else " (signal)"
        L.append(f"| {name}{flag} | {yn}, {ym} | {nn}, {nm} |")
    L += ["", "## Pillars (metrics.jsonl, one row per job)", "", "| Pillar | Videos | Median | Mean |", "|---|---|---|---|"]
    L += [f"| {p} | {n} | {m} | {a} |" for p, n, m, a in ev["pillars"]] or ["| none yet | 0 | | |"]
    h = ev["hold"]
    gates = ", ".join(f"{g} x{c}" for g, c in h.get("top_failing_gates", [])) or "none recorded"
    L += ["", "## Production", "", f"- Last 7 days: {h.get('videos', 0)} videos, {h.get('held', 0)} held ({round(h.get('hold_rate', 0) * 100)}%). "
          f"Top failing gates: {gates}.",
          f"- Phone lane posts recorded: " + (", ".join(f"{k} {v}" for k, v in sorted(ev['phone'].items())) or "none") + ".", ""]
    if trend:
        L += ["## Trend (one row per run, newest last)", "", "| Run (UTC) | Snapshot | Shorts | Mean | Median | <=5 views | Hold rate | Subscribers |", "|---|---|---|---|---|---|---|---|"]
        L += [f"| {t['at'][:16]} | {t['snapshot'] or '-'} | {t['shorts']} | {t['mean']} | {t['median']} | {t['zero']} | "
              f"{round((t['hold_rate'] or 0) * 100)}% | {t['subscribers'] if t['subscribers'] is not None else '-'} |" for t in trend[-8:]]
        L.append("")
    L.append(END)
    return "\n".join(L)


JUDGMENT_HEAD = "## Judgment (written by the review, kept between runs)"
JUDGMENT_STUB = (f"{JUDGMENT_HEAD}\n\n*No review has been written yet. The performance review (skill `faceless-performance-review`) fills this section: "
                 "what is working, what is not, the next bets, the owner's decisions, and dated checkpoints.*\n")


def write() -> dict:
    today = config.today_utc().isoformat()
    ev = evidence(today)
    trend = read_jsonl(LOG)
    row = trend_row(ev)
    if trend and trend[-1]["at"][:10] == row["at"][:10] and trend[-1].get("snapshot") == row["snapshot"]:
        trend[-1] = row                                 # one row per day: a re-run the same day replaces it
    else:
        trend.append(row)
    write_atomic(LOG, "".join(json.dumps(t) + "\n" for t in trend))
    block = render(ev, trend)
    if OUT.exists() and BEGIN in OUT.read_text(encoding="utf-8") and END in OUT.read_text(encoding="utf-8"):
        text = OUT.read_text(encoding="utf-8")
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        text = head + block + tail
    else:
        head = ("# Channel strategy: what is working, and what changes next\n\n"
                "This file is kept current from the channel's own numbers. The top block is rewritten by `python -m faceless strategy`, "
                "which the weekly scout runs. The judgment below it is written by the performance review and kept between runs.\n\n")
        text = head + block + "\n\n" + JUDGMENT_STUB
    write_atomic(OUT, text)
    return {"path": str(OUT), "trend_rows": len(trend), "snapshot": ev["snapshot"], "shorts": ev["shorts"]}
